"""Tests for the Microsoft Copilot and BLS job outlook panels (ROADMAP 10.15, 10.16). Run from the project root:

    python -m unittest discover -s tests
"""

import csv
import unittest

from career_rag.config import BLS_DIR, MICROSOFT_SCORES_PATH
from career_rag.ip_ai_impact import AI_REASON, build_ai_impact_for_occupation, nem_code
from career_rag.ui_i18n import bls_outlook_lines, jobs_text, microsoft_lines, signed_percent


class CodesTest(unittest.TestCase):
    def test_careers_map_to_bls_codes(self):
        self.assertEqual(nem_code("15-2041.01"), "15-2041")  # its first seven characters
        self.assertEqual(nem_code("13-1022.00"), "13-1020")  # one of the 34 BLS groups differently
        self.assertEqual(nem_code("25-2056.00"), "25-2052")

    def test_microsoft_and_bls_use_the_same_codes(self):
        with MICROSOFT_SCORES_PATH.open(encoding="utf-8", newline="") as handle:
            microsoft = {row["soc_code"] for row in csv.DictReader(handle)}
        with (BLS_DIR / "projections_2025_35.csv").open(encoding="utf-8", newline="") as handle:
            bls = {row["nem_code"] for row in csv.DictReader(handle)}
        self.assertLessEqual(len(microsoft - bls), 5)  # e.g. "All Other" codes one of them leaves out


class NumbersTest(unittest.TestCase):
    def test_jobs_and_signed_percents_in_both_languages(self):
        self.assertEqual(jobs_text(31.3), "31,300")
        self.assertEqual(jobs_text(2666, "tr"), "2.666.000")
        self.assertEqual(signed_percent(11.0), "+11%")
        self.assertEqual(signed_percent(-5.3, "tr"), "-%5,3")

    def test_statisticians(self):
        ai = build_ai_impact_for_occupation("15-2041.00")
        self.assertEqual(bls_outlook_lines(ai["bls_outlook"])[0],
                         "BLS projects US employment in this occupation to go from about 31,300 jobs in 2025 to 34,700 "
                         "in 2035 (+11%); for all US jobs together: +3.5%.")
        self.assertIn("which also covers one other career", bls_outlook_lines(ai["bls_outlook"])[-1])  # Biostatisticians
        self.assertTrue(microsoft_lines(ai["microsoft_applicability"])[0].startswith(
            "Microsoft's AI applicability score: 0.32, number 71 of the 785"))
        self.assertLessEqual(len(ai["microsoft_applicability"]["activities"]), 5)


class BlsReasonsTest(unittest.TestCase):
    def test_industry_reasons_are_kept_only_when_they_mention_ai_or_automation(self):
        with (BLS_DIR / "factors_2025_35.csv").open(encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle):
                if row["industry_code"] != "TE1000":
                    self.assertRegex(row["factor"], AI_REASON, row["nem_code"])

    def test_the_all_industries_reason_comes_first(self):
        reasons = build_ai_impact_for_occupation("51-4121.00")["bls_outlook"]["reasons"]  # welders: industry rows only
        self.assertTrue(reasons and all(item["industry"] for item in reasons))
        reasons = build_ai_impact_for_occupation("27-3043.00")["bls_outlook"]["reasons"]
        self.assertEqual(reasons[0]["industry"], "")
        self.assertTrue(reasons[0]["ai"])  # "more written works are generated by artificial intelligence (AI) tools"


if __name__ == "__main__":
    unittest.main()
