#!/usr/bin/env python3
"""Compare ways of ranking "Top Matches" for the baseline profiles (ROADMAP 2.6, D11).

For each profile and Job Zone, side by side:
  today  the app's current first 5 (candidate pool in PDF order, i.e. alphabetical)
  A1     the same candidate pool, ordered by similarity: Pearson correlation between the
         user's 6 RIASEC scores and the occupation's 6 O*NET interest scores (scale OI)
  A2     the same similarity, over all O*NET occupations in that Job Zone
  B      O*NET's official Interest Profiler careers (API, needs ONET_API_KEY in .env)

Writes docs/analysis/top_matches_ranking_comparison.md. Read-only otherwise.
"""

from __future__ import annotations

import json
import os
import sys
import urllib.parse
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(PROJECT_ROOT / "scripts"))
os.environ["OPENAI_API_KEY"] = ""  # the report's LLM text is not needed here

import duckdb  # noqa: E402
from dotenv import load_dotenv  # noqa: E402

import make_baseline  # noqa: E402
from career_rag.config import ONET_DUCKDB_PATH  # noqa: E402
from career_rag.interest_profiler_local import RIASEC_INTERESTS  # noqa: E402
from career_rag.ip_final_report import _build_profile_used, _candidate_groups_from_profile  # noqa: E402
from career_rag.occupation_aliases import build_occupation_index, resolve_career_alias  # noqa: E402

OUTPUT = PROJECT_ROOT / "docs" / "analysis" / "top_matches_ranking_comparison.md"
TOP = 5
OI_ELEMENTS = dict(zip(["1.B.1.a", "1.B.1.b", "1.B.1.c", "1.B.1.d", "1.B.1.e", "1.B.1.f"], RIASEC_INTERESTS))


def pearson(xs: list[float], ys: list[float]) -> float:
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    var = (sum((x - mx) ** 2 for x in xs) * sum((y - my) ** 2 for y in ys)) ** 0.5
    return cov / var if var else 0.0


def load_onet() -> tuple[dict[str, list[float]], dict[str, int], dict[str, str]]:
    con = duckdb.connect(str(ONET_DUCKDB_PATH), read_only=True)
    profiles: dict[str, dict[str, float]] = {}
    for code, element, value in con.execute(
        "select onetsoc_code, element_id, data_value from career_interest_types where scale_id = 'OI'"
    ).fetchall():
        profiles.setdefault(code, {})[OI_ELEMENTS[element]] = float(value)
    interest = {code: [p[i] for i in RIASEC_INTERESTS] for code, p in profiles.items() if len(p) == 6}
    zones = {code: int(zone) for code, zone in con.execute("select onetsoc_code, job_zone from job_zones").fetchall()}
    titles = dict(con.execute("select onetsoc_code, title from occupation_data").fetchall())
    return interest, zones, titles


def official_careers(scores: dict[str, int], zone: int, key: str) -> list[tuple[str, str, str]]:
    # Checkbox counts (0-10) x 4 = the API's 0-40 scale: what it computes if every checked
    # activity were "Strongly Like" (4 points) and every unchecked one "Strongly Dislike" (0).
    params = {name.lower(): scores[name] * 4 for name in RIASEC_INTERESTS}
    params.update(zone=zone, start=1, end=1000)
    url = "https://api-v2.onetcenter.org/mnm/interestprofiler/careers?" + urllib.parse.urlencode(params)
    request = urllib.request.Request(url, headers={"X-API-Key": key, "Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=30) as response:
        body = json.loads(response.read().decode("utf-8"))
    return [(c["code"], c["title"], c.get("fit", "")) for c in body.get("career", [])]


def main() -> int:
    load_dotenv(PROJECT_ROOT / ".env")
    key = os.environ.get("ONET_API_KEY", "")
    if not key:
        sys.exit("ONET_API_KEY is missing in .env")
    interest, zones, titles = load_onet()
    index = build_occupation_index()
    lines = [
        "# Top Matches: ranking comparison (ROADMAP 2.6, decision D11)",
        "",
        f"Generated by `scripts/analysis/compare_top_match_rankings.py`. Top {TOP} per Job Zone.",
        "After each title: its similarity (Pearson r) with the user's RIASEC scores, then the fit",
        "O*NET's official Interest Profiler gives it for this profile and zone ('not listed' = not in",
        "O*NET's list). O*NET's API uses O*NET 31.0; the local database is 30.3, so a few Job Zones differ.",
        "",
        "O*NET's published rule (Gregory & Lewis 2016, 'Linking Client Assessment Profiles to O*NET",
        "Occupational Profiles', pp. 11-12): Pearson r, Best fit r >= .729, Great fit r >= .608, Good fit",
        "0 <= r < .608 only to fill the list up to 10 per Job Zone; alphabetical within each fit.",
        "",
    ]
    for name in make_baseline.PROFILES:
        profile = make_baseline.build_profile(name)
        scores = profile["riasec_scores"]
        user = [float(scores[i]) for i in RIASEC_INTERESTS]
        report = json.loads(make_baseline.build_report(name))
        groups = _candidate_groups_from_profile(profile, _build_profile_used(profile, ""))
        lines += [f"## {name}", "", "Scores: " + ", ".join(f"{i[0]}={scores[i]}" for i in RIASEC_INTERESTS), ""]
        for group in groups:
            zone = int(group["job_zone"])
            r = lambda code: pearson(user, interest[code]) if code in interest else float("nan")  # noqa: E731
            today = [m for m in report["top_matches"] if m.get("match_group") == group["label"]][:TOP]
            today_rows = [(m["onet_soc_code"], m["display_title"]) for m in today]
            pool = {}
            for c in group["candidates"]:
                code = resolve_career_alias(c.get("career_title", ""), index).get("onet_soc_code")
                if code and code not in pool:
                    pool[code] = c.get("career_title")
            a1 = sorted(pool.items(), key=lambda kv: -r(kv[0]))[:TOP]
            db_zone = max(zone, 2)  # O*NET 30.3 merged zones 1 and 2 (stored as 2); ROADMAP 2.8
            a2 = sorted((c for c, z in zones.items() if z == db_zone and c in interest), key=lambda c: -r(c))[:TOP]
            a2_rows = [(c, titles.get(c, c)) for c in a2]
            b = official_careers(scores, zone, key)
            fit = {c: f for c, _, f in b}
            b_rows = [(c, t) for c, t, _ in b[:TOP]]
            columns = {"Today (alphabetical)": today_rows, "A1: same pool, by similarity": a1,
                       "A2: all occupations in zone, by similarity": a2_rows,
                       "B: O*NET official (alphabetical within fit)": b_rows}
            bands = ", ".join(f"{n} {f}" for f in ("Best", "Great", "Good") if (n := sum(v == f for v in fit.values())))
            lines += [f"### {group['label']} (Job Zone {zone}, app pool {len(pool)} careers, O*NET list: {bands})", "",
                      "| # | " + " | ".join(columns) + " |", "|---|" + "---|" * len(columns)]
            for i in range(TOP):
                cells = []
                for rows in columns.values():
                    if i < len(rows):
                        code, title = rows[i]
                        cells.append(f"{title} ({r(code):.2f}, {fit.get(code, 'not listed')})")
                    else:
                        cells.append("")
                lines.append(f"| {i + 1} | " + " | ".join(cells) + " |")
            band_r = {f: [r(c) for c in fit if fit[c] == f and c in interest] for f in ("Best", "Great", "Good")}
            lines += ["", "Similarity range of O*NET's bands (full list): " + ", ".join(
                f"{f} {min(v):.2f}–{max(v):.2f}" for f, v in band_r.items() if v)]
            lines += ["", "O*NET 'Best' fits in each top 5: " + ", ".join(
                f"{n.split(':')[0]} {sum(fit.get(c) == 'Best' for c, _ in rows)}/{len(rows)}" for n, rows in columns.items()),
                "", "Average similarity of the 5 shown: " + ", ".join(
                f"{n.split(':')[0]} {sum(r(c) for c, _ in rows) / len(rows):.2f}" for n, rows in columns.items()), ""]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
